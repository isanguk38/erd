/** ENUM 값 바꾸기: 추가만이면 ADD VALUE, 빼거나 순서를 바꾸면 타입을 다시 만들고 컬럼을 옮긴다 */
function alterEnum(before: EnumType, after: EnumType, usages: { table: string; column: Column }[]): string[] {
  const name = pgEnumTypeName(after.name);
  const added = enumAdditions(before.values, after.values);
  // 값 추가만: ALTER TYPE ... ADD VALUE (위치 지정)
  if (added) {
    return added.map((a) => `ALTER TYPE ${name} ADD VALUE ${literal(a.value)}${a.before ? ` BEFORE ${literal(a.before)}` : a.after ? ` AFTER ${literal(a.after)}` : ''}`);
  }
  // 값을 빼거나 순서를 바꾸면: 옛 타입 이름을 바꾸고 새로 만든 뒤, 쓰는 컬럼을 새 타입으로 옮기고 옛 타입을 지운다
  const old = pgEnumTypeName(`${after.name.replace(/"/g, '')}_old`);
  const statements = [`ALTER TYPE ${name} RENAME TO ${old}`, `CREATE TYPE ${name} AS ENUM (${after.values.map((v) => literal(v)).join(', ')})`];
  for (const u of usages) {
    const c = q(u.column.name);
    const t = q(u.table);
    const def = u.column.defaultValue?.trim();
    // 기본값이 옛 타입을 가리키면 타입을 바꿀 수 없어 잠깐 지웠다가 다시 건다
    if (def) statements.push(`ALTER TABLE ${t} ALTER COLUMN ${c} DROP DEFAULT`);
    statements.push(`ALTER TABLE ${t} ALTER COLUMN ${c} TYPE ${name} USING ${c}::text::${name}`);
    if (def) statements.push(`ALTER TABLE ${t} ALTER COLUMN ${c} SET DEFAULT ${def}`);
  }
  statements.push(`DROP TYPE ${old}`);
  return statements;
}

export const postgresql: Dialect = {
  id: 'postgresql',
  label: 'PostgreSQL',
  ddlGrammar: { family: 'postgresql', backslashEscapes: false, hidesFkIndexes: false, keepsPrimaryKeyName: true, quotedTypeNames: true },
  typeSuggestions: [
    'BIGINT', 'INTEGER', 'SMALLINT', 'NUMERIC', 'DOUBLE PRECISION', 'REAL', 'BOOLEAN',
    'VARCHAR', 'CHAR', 'TEXT', 'DATE', 'TIMESTAMP', 'TIMESTAMPTZ', 'TIME',
    'UUID', 'JSON', 'JSONB', 'BYTEA',
  ],

  quote: q,
  renderType,
  normalizeAction: (action) => action,
  normalizeDefault(value) {
    if (value === null) return null;
    // 'Y'::character varying → 'Y', 'ISSUED'::"BillingStatus" → 'ISSUED'
    const stripped = value.replace(/::([a-z_ ]+|"(?:[^"]|"")+")(\[\])?$/i, '');
    const v = normalizeDefaultCommon(stripped);
    if (v === 'NOW()') return 'CURRENT_TIMESTAMP';
    return v;
  },

  createTable(table) {
    const lines = table.columns.map((c) => '  ' + columnDefinition(c));
    const pk = primaryKeyColumns(table);
    if (pk.length) lines.push(`  CONSTRAINT ${q(pkName(table))} PRIMARY KEY (${pk.map((c) => q(c.name)).join(', ')})`);
    const statements = [`CREATE TABLE ${q(table.name)} (\n${lines.join(',\n')}\n)`];
    if (sqlComment(table)) statements.push(tableComment(table));
    for (const c of table.columns) if (sqlComment(c)) statements.push(columnComment(table, c));
    return statements;
  },
  dropTable: (table) => [`DROP TABLE ${q(table.name)}`],
  renameTable: (from, to) => [`ALTER TABLE ${q(from.name)} RENAME TO ${q(to.name)}`],
  setTableComment: (table) => [tableComment(table)],

  addColumn(table, column) {
    const statements = [`ALTER TABLE ${q(table.name)} ADD COLUMN ${columnDefinition(column)}`];
    if (sqlComment(column)) statements.push(columnComment(table, column));
    return statements;
  },
  dropColumn: (table, column) => [`ALTER TABLE ${q(table.name)} DROP COLUMN ${q(column.name)}`],
  alterColumn(table, before, after, changed) {
    const t = q(table.name);
    const statements: string[] = [];
    if (changed.includes('name')) statements.push(`ALTER TABLE ${t} RENAME COLUMN ${q(before.name)} TO ${q(after.name)}`);
    const c = q(after.name);
    const actions: string[] = [];
    // 직접 만든 타입(ENUM)으로·에서 바꾸면: 글자(text)를 거쳐 바꾸고, 옛 타입을 쓰는 기본값은 잠깐 지웠다가 다시 건다
    // (PostgreSQL에는 ENUM 사이의 캐스트가 없고, 옛 타입의 기본값은 새 타입으로 바뀌지 않아 실패한다)
    const viaText = changed.includes('type') && (isUserType(before) || isUserType(after));
    const keepDefault = viaText && before.defaultValue?.trim() && !changed.includes('defaultValue') && !after.autoIncrement ? after.defaultValue?.trim() : '';
    if (viaText && before.defaultValue?.trim()) statements.push(`ALTER TABLE ${t} ALTER COLUMN ${c} DROP DEFAULT`);
    if (changed.includes('type')) {
      const type = renderType(after);
      actions.push(`ALTER COLUMN ${c} TYPE ${type} USING ${c}::${viaText ? 'text::' : ''}${type}`);
    }
    if (changed.includes('autoIncrement')) {
      if (after.autoIncrement) {
        if (before.defaultValue) actions.push(`ALTER COLUMN ${c} DROP DEFAULT`);
        actions.push(`ALTER COLUMN ${c} ADD GENERATED BY DEFAULT AS IDENTITY`);
      } else {
        actions.push(`ALTER COLUMN ${c} DROP IDENTITY IF EXISTS`);
      }
    }
    if (changed.includes('nullable')) {
      actions.push(after.nullable && !after.primaryKey && !after.autoIncrement ? `ALTER COLUMN ${c} DROP NOT NULL` : `ALTER COLUMN ${c} SET NOT NULL`);
    }
    if (changed.includes('defaultValue') && !after.autoIncrement) {
      const v = after.defaultValue?.trim();
      actions.push(v ? `ALTER COLUMN ${c} SET DEFAULT ${v}` : `ALTER COLUMN ${c} DROP DEFAULT`);
    }
    if (actions.length) statements.push(`ALTER TABLE ${t} ${actions.join(', ')}`);
    if (keepDefault) statements.push(`ALTER TABLE ${t} ALTER COLUMN ${c} SET DEFAULT ${keepDefault}`);
    if (changed.includes('comment')) statements.push(columnComment(table, after));
    return statements;
  },
  changePrimaryKey(before, after) {
    const newPk = primaryKeyColumns(after);
    const actions: string[] = [];
    if (primaryKeyColumns(before).length) actions.push(`DROP CONSTRAINT ${q(pkName(before))}`);
    if (newPk.length) actions.push(`ADD CONSTRAINT ${q(`${after.name}_pkey`)} PRIMARY KEY (${newPk.map((c) => q(c.name)).join(', ')})`);
    return actions.length ? [`ALTER TABLE ${q(after.name)} ${actions.join(', ')}`] : [];
  },

  features: {
    // DB 객체: 뷰·구체화 뷰·함수·프로시저·트리거. 함수·프로시저는 CREATE OR REPLACE로 바꾼다 (트리거가 쓰는 함수를 지우지 않게)
    objects: dbObjectsModule({
      kinds: ['view', 'materializedView', 'function', 'procedure', 'trigger'],
      quote: q,
      drop: {
        view: (o, q) => `DROP VIEW IF EXISTS ${q(o.name)}`,
        materializedView: (o, q) => `DROP MATERIALIZED VIEW IF EXISTS ${q(o.name)}`,
        function: (o, q) => `DROP FUNCTION IF EXISTS ${q(o.name)}`,
        procedure: (o, q) => `DROP PROCEDURE IF EXISTS ${q(o.name)}`,
        trigger: (o, q) => `DROP TRIGGER IF EXISTS ${q(o.name)} ON ${q(o.table ?? '')}`,
      },
      replaceable: ['function', 'procedure'],
      templates: {
        view: (n, t) => `CREATE VIEW ${q(n)} AS
SELECT *
FROM ${q(t)}`,
        materializedView: (n, t) => `CREATE MATERIALIZED VIEW ${q(n)} AS
SELECT *
FROM ${q(t)}`,
        function: (n) => `CREATE OR REPLACE FUNCTION ${q(n)}(p integer)
RETURNS integer
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN p;
END;
$$`,
        procedure: (n) => `CREATE OR REPLACE PROCEDURE ${q(n)}()
LANGUAGE plpgsql
AS $$
BEGIN
  NULL;
END;
$$`,
        trigger: (n, t) => `CREATE TRIGGER ${q(n)}
BEFORE UPDATE ON ${q(t)}
FOR EACH ROW
EXECUTE FUNCTION trigger_function_name()`,
      },
    }),
    enum: enumAsTypeObject({
      typeName: pgEnumTypeName,
      create: (e) => [`CREATE TYPE ${pgEnumTypeName(e.name)} AS ENUM (${e.values.map((v) => literal(v)).join(', ')})`],
      drop: (e) => [`DROP TYPE ${pgEnumTypeName(e.name)}`],
      alter: alterEnum,
      help: 'CREATE TYPE 이름 AS ENUM (...)으로 따로 만들고, 컬럼은 그 타입을 씁니다. 값 추가는 ALTER TYPE ... ADD VALUE, 값을 빼거나 순서를 바꾸면 타입을 다시 만들어 컬럼을 옮깁니다.',
    }),
    check: standardCheck(q),
    expressionIndex: {
      example: (col) => `lower(${col})`,
      hint: "예) lower(email), (metadata ->> 'sitecd'), to_tsvector('simple', body)",
      warn: (e) => (/->>?\s*'\$/.test(e) ? `식에 MySQL JSON 경로('$.키') 문법이 있어 PostgreSQL에서는 실패할 수 있습니다: ${e}` : undefined),
    },
    partialIndex: { placeholder: 'WHERE 뒤 조건 (부분 인덱스). 예) deleted_at IS NULL' },
    indexMethods: { methods: ['hash', 'gin', 'gist', 'spgist', 'brin'], label: (m) => m },
    generated: { stored: true },
    fkOnUpdate: { actions: ['NO ACTION', 'RESTRICT', 'CASCADE', 'SET NULL', 'SET DEFAULT'] },
  },
  traits: {},
  types: postgresTypes,
  connection: { port: 5432, databaseLabel: '데이터베이스', databasePlaceholder: 'postgres', schemaPlaceholder: 'public', transactional: true },
  seed: {
    boolean: (v) => (v ? 'TRUE' : 'FALSE'),
    binary: (h) => `decode('${h}', 'hex')`,
    text: (s) => literal(s),
    dateTime: (s) => literal(s),
    multiRow: true,
    // IDENTITY 번호를 직접 넣으면 시퀀스가 그대로라, 다음 INSERT가 겹치지 않게 가장 큰 번호로 맞춘다
    resetIdentity: (t, c) => `SELECT setval(pg_get_serial_sequence(${literal(q(t))}, ${literal(c)}), (SELECT MAX(${q(c)}) FROM ${q(t)}))`,
  },
  safety: { countUpTo: limitCount, lengthFn: 'char_length', notNumeric: (col, integer) => `${col} IS NOT NULL AND ${col}::text !~ '${numericRegex(integer)}'` },
  createIndex(table, index) {
    // PostgreSQL에 있는 방식만 쓴다 (MySQL의 fulltext 등은 일반 인덱스로 만들고 주의를 단다)
    const m = index.method?.trim().toLowerCase() ?? '';
    const method = m && (postgresql.features.indexMethods?.methods ?? []).includes(m) ? ` USING ${m}` : '';
    return [`CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${q(indexName(table, index))} ON ${q(table.name)}${method} (${indexKeys(table, index, q)})${indexWhere(index)}`];
  },
  dropIndex: (table, index) =>
    index.isConstraint
      ? [`ALTER TABLE ${q(table.name)} DROP CONSTRAINT ${q(indexName(table, index))}`]
      : [`DROP INDEX ${q(indexName(table, index))}`],

  addForeignKey(schema, relation) {
    const { from, to } = relationTables(schema, relation);
    const fromCols = columnNames(from, relation.fromColumnIds).map(q).join(', ');
    const toCols = columnNames(to, relation.toColumnIds).map(q).join(', ');
    let sql = `ALTER TABLE ${q(from.name)} ADD CONSTRAINT ${q(relationName(schema, relation))} FOREIGN KEY (${fromCols}) REFERENCES ${q(to.name)} (${toCols})`;
    if (relation.onDelete !== 'NO ACTION') sql += ` ON DELETE ${relation.onDelete}`;
    if (relation.onUpdate !== 'NO ACTION') sql += ` ON UPDATE ${relation.onUpdate}`;
    return [sql];
  },
  dropForeignKey(schema, relation) {
    const { from } = relationTables(schema, relation);
    return [`ALTER TABLE ${q(from.name)} DROP CONSTRAINT ${q(relationName(schema, relation))}`];
  },
};
