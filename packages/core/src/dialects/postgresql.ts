/** 길이를 붙이지 않는 타입 (MySQL에서 가져온 INT(11) 같은 표시 폭 제거) */
const NO_LENGTH = new Set([
  'INTEGER', 'BIGINT', 'SMALLINT', 'BOOLEAN', 'TEXT', 'BYTEA', 'DATE', 'REAL',
  'DOUBLE PRECISION', 'JSON', 'JSONB', 'UUID',
]);

const RESERVED = new Set([
  'all', 'and', 'any', 'array', 'as', 'asc', 'case', 'check', 'column', 'constraint', 'create',
  'default', 'desc', 'distinct', 'do', 'else', 'end', 'for', 'foreign', 'from', 'grant', 'group',
  'having', 'in', 'into', 'is', 'join', 'key', 'limit', 'not', 'null', 'offset', 'on', 'or',
  'order', 'primary', 'references', 'select', 'table', 'then', 'to', 'union', 'unique', 'user',
  'using', 'when', 'where', 'with',
]);

function q(name: string): string {
  if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name)) return name;
  return '"' + name.replace(/"/g, '""') + '"';
}

/**
 * 따옴표로 감싼 사용자 타입 ("BillingStatus")은 대소문자를 구분하므로 그대로 둔다.
 * 다만 소문자만이면 따옴표가 없는 것과 같으므로 다른 타입처럼 대문자로 맞춘다 ("mood" = mood).
 */
function quotedType(type: string): string | null {
  const t = type.trim().replace(/^public\./i, '');
  const m = t.match(/^"((?:[^"]|"")+)"(\[\])?$/);
  if (!m) return null;
  const inner = m[1]!;
  return /^[a-z_][a-z0-9_]*$/.test(inner) ? `${inner.toUpperCase()}${m[2] ?? ''}` : t;
}

function renderType(column: Column): string {
  const quoted = quotedType(column.type);
  if (quoted) return quoted;
  // PostgreSQL에는 UNSIGNED가 없다
  const raw = column.type.trim().toUpperCase().replace(/\s+(UNSIGNED|ZEROFILL)\b/g, '');
  const type = TYPE_MAP[raw] ?? raw;
  const length = NO_LENGTH.has(type) ? '' : column.length;
  return typeWithLength(type, length);
}

function columnDefinition(column: Column): string {
  const parts = [q(column.name), renderType(column)];
  const generated = column.generated?.expression.trim();
  if (generated) {
    parts.push(`GENERATED ALWAYS AS (${quoteExpression(generated, q)}) STORED`);
    if (!column.nullable || column.primaryKey) parts.push('NOT NULL');
    return parts.join(' ');
  }
  if (column.autoIncrement) parts.push('GENERATED BY DEFAULT AS IDENTITY');
  if (!column.nullable || column.primaryKey) parts.push('NOT NULL');
  if (column.defaultValue !== null && column.defaultValue.trim() !== '' && !column.autoIncrement) {
    parts.push(`DEFAULT ${column.defaultValue.trim()}`);
  }
  return parts.join(' ');
}

function columnComment(table: Table, column: Column): string {
  const comment = sqlComment(column);
  return `COMMENT ON COLUMN ${q(table.name)}.${q(column.name)} IS ${comment ? literal(comment) : 'NULL'}`;
}

function tableComment(table: Table): string {
  const comment = sqlComment(table);
  return `COMMENT ON TABLE ${q(table.name)} IS ${comment ? literal(comment) : 'NULL'}`;
}

function pkName(table: Table): string {
  return table.primaryKeyName || `${table.name}_pkey`;
}

/** PostgreSQL 타입 정보 (컬럼 타입 검사가 쓴다) */
/**
 * 직접 만든 타입(ENUM 등)인지: 따옴표로 감싼 타입이거나 PostgreSQL 기본 타입이 아닌 것.
 * 이런 타입끼리는 바로 바꾸는 캐스트가 없어(예: 한 ENUM → 다른 ENUM) 글자(text)를 거쳐 바꿔야 한다.
 */
function isUserType(column: Column): boolean {
  if (quotedType(column.type)) return true;
  const raw = column.type.trim().toUpperCase().replace(/\[\]$/, '').split(/[\s(]/)[0] ?? '';
  return Boolean(raw) && !postgresTypes.known.has(TYPE_MAP[raw] ?? raw);
}

